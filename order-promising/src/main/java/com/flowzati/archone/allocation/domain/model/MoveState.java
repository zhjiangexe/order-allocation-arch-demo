package com.flowzati.archone.allocation.domain.model;

/**
 * 一段搬運走到哪了。
 *
 * <p>值域刻意只有四個，與 Odoo 的 {@code confirmed} / {@code assigned} / {@code done} /
 * {@code cancel} 一對一。三個沒有取的同樣重要，而且**理由分成兩種**：
 *
 * <ul>
 *   <li><b>沒有「等上一段」</b>（Odoo 的 {@code waiting}）——<b>因為本系統是純 MTS。</b>
 *       Odoo 的 {@code _action_confirm()} 就是這樣分岔的：move 有上游（{@code move_orig_ids}）
 *       才進 {@code waiting}，沒有就進 {@code confirmed}。我們的出庫是「庫存位置 → 客戶」單段，
 *       沒有上游，所以連 Odoo 自己算出來的也會是 {@code confirmed}。
 *       <p>會產生它的是多段出庫（ship 等 pick）與 MTO（出庫綁定某一筆進貨），兩者都沒有。
 *       <b>入庫走 move 之後也不會變</b>：補貨只是把數量加進庫存列，佇列重跑鎖定就配到了——
 *       move 等的是「庫存出現」，不是「某一段特定的搬運完成」，而那正是 MTS 的定義。
 *       <p>它與「哪一段接在哪一段之後」的關聯表是同一件事的兩半：沒有鏈結，就沒有「等誰」
 *       可以表達。
 *   <li><b>沒有「部分可用」</b>（{@code partially_available}）——ship-complete 下一張單整批配到
 *       或整批不配，部分可用不是一個會停留的狀態。
 *   <li><b>沒有「草稿」</b>（{@code draft}）——<b>這一個的性質不同</b>：前兩個在本系統的規則下
 *       不可能發生，草稿只是現在還沒有。Odoo 有它是因為單據可以先組出來、編輯，再按下按鈕才
 *       確認；本系統的搬運由收單事件建立，而<b>那個事件本身就是確認</b>——上游早就下單了，
 *       這裡沒有可編輯的階段。建一個草稿再在同一個交易裡確認掉，會造出一個沒有人觀察得到的
 *       狀態。（Odoo 的銷售訂單路徑也不會停在草稿：建完 move 就接著確認。草稿主要來自手動與
 *       畫面上的路徑。）哪天出庫要先起草再放行，它就得回來——屆時要加的是狀態，不是另一張
 *       「草稿單」的表。
 * </ul>
 */
public enum MoveState {

  /** 要貨，還沒拿到。這就是待配佇列。 */
  CONFIRMED,

  /** 貨已鎖定。此時必有 move line 說明鎖了哪幾批。 */
  ASSIGNED,

  /**
   * 貨真的動了。
   *
   * <p><b>此階段沒有任何產生者</b>——出貨屬 R7。它現在就存在，是因為下游的謂詞要一次寫對：
   * 待配需求問的是「這條行有沒有 move」，而已完成的 move 也算有。少了它，R7 每一張已出貨的
   * 單都會重新變成待接手的需求，而**那一刻不會有任何測試失敗**。
   */
  DONE,

  /** 這一段不做了。取消時進入，其 move line 一併刪除。 */
  CANCELLED
}
